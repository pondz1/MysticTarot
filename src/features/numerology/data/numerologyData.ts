export function convertInputToDigits(input: string): string {
  let result = '';
  for (const char of input) {
    if (/\d/.test(char)) {
      result += char;
    } else if (THAI_CHAR_MAP[char]) {
      result += THAI_CHAR_MAP[char];
    }
  }
  return result;
}

export function analyzeNumerologyInput(input: string) {
  const clean = convertInputToDigits(input);
  if (clean.length < 1) {
    return null;
  }

  let sum = 0;
  for (let i = 0; i < clean.length; i++) {
    sum += parseInt(clean[i], 10);
  }

  // Calculate digit pairs (00-99 full coverage)
  const pairs: PairNumberAnalysis[] = [];
  if (clean.length === 1) {
    const singlePair = '0' + clean;
    if (COMMON_PAIR_ANALYSIS[singlePair]) {
      pairs.push(COMMON_PAIR_ANALYSIS[singlePair]);
    }
  } else {
    for (let i = 0; i < clean.length - 1; i++) {
      const pairStr = clean.slice(i, i + 2);
      if (COMMON_PAIR_ANALYSIS[pairStr]) {
        pairs.push(COMMON_PAIR_ANALYSIS[pairStr]);
      }
    }
  }

  const sumInfo = getNumerologySumMeaning(sum);

  return {
    inputNumber: input,
    cleanDigits: clean,
    sumValue: sum,
    sumMeaning: sumInfo,
    pairAnalyses: pairs,
    overallGrade: sumInfo.grade,
    summaryText: sumInfo.description,
  };
}

